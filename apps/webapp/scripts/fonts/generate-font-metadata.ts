/**
 * Generates the font metadata used to load the self-hosted web fonts
 * without a visible flicker:
 *
 * - `src/styles/fonts.generated.ts`: for every font, the file to preload
 *   (latin subset of the regular, non-italic face)
 * - `src/styles/fonts-fallback.css`: for every font, a "<Name> Fallback"
 *   @font-face that points to a local system font (Arial / Times New Roman)
 *   with size-adjust and ascent/descent/line-gap overrides, so the fallback
 *   takes up the same space as the web font and the swap barely shows.
 *
 * The metrics are computed exactly like `next/font` does it.
 *
 * Run it after adding, removing or replacing a font:
 *   bun run fonts:generate
 */
import { readFile, writeFile } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
// next ships fontkit and its fallback calculation, reuse them
import fontkitModule from 'next/dist/compiled/@next/font/dist/fontkit/index.js';
import { getFallbackMetricsFromFontFile } from 'next/dist/compiled/@next/font/dist/local/get-fallback-metrics-from-font-file.js';
import { allFonts } from '../../src/styles/fonts.ts';

// same unwrapping as in next/font's local loader
const fontkitDefault = (fontkitModule as any).default ?? fontkitModule;
const fontFromBuffer: (buffer: Buffer) => any =
  fontkitDefault.default ?? fontkitDefault;

const webappRoot = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const fontsCssDir = join(webappRoot, 'src/styles/fonts');
const publicDir = join(webappRoot, 'public');

type FontFace = {
  family: string;
  style: string;
  weight: number;
  url: string;
  unicodeRange: string | null;
};

const parseFontFaces = (css: string): FontFace[] =>
  [...css.matchAll(/@font-face\s*{([^}]*)}/g)].map(([, body]) => {
    const prop = (name: string) =>
      body
        .match(new RegExp(`(?:^|;|\\s)${name}\\s*:\\s*([^;]+)`))?.[1]
        ?.trim() ?? null;
    return {
      family: prop('font-family')!.replace(/['"]/g, ''),
      style: prop('font-style') ?? 'normal',
      weight: Number(prop('font-weight') ?? 400),
      url: prop('src')!.match(/url\(["']?([^"')]+)["']?\)/)![1],
      unicodeRange: prop('unicode-range')?.replace(/\s+/g, ' ') ?? null,
    };
  });

const coversBasicLatin = ({ unicodeRange }: FontFace) =>
  !unicodeRange || /U\+0+-0*FF\b/i.test(unicodeRange);

/**
 * The face the browser uses for regular body text (weight 400), following
 * the CSS font matching algorithm: 400, then 500, then lighter weights
 * descending, then heavier weights ascending.
 */
const pickRegularFace = (faces: FontFace[]) => {
  const candidates = faces.filter(
    (face) => face.style === 'normal' && coversBasicLatin(face)
  );
  const rank = ({ weight }: FontFace) =>
    weight === 400
      ? 0
      : weight === 500
        ? 1
        : weight < 400
          ? 1000 - weight
          : 2000 + weight;
  return candidates.sort((a, b) => rank(a) - rank(b))[0];
};

const metadata: Record<string, { preload: string }> = {};
const fallbackCss: string[] = [];

for (const font of allFonts) {
  const css = await readFile(
    join(fontsCssDir, font.directory, 'style.css'),
    'utf8'
  );
  const faces = parseFontFaces(css).filter(
    ({ family }) => family === font.name
  );
  if (!faces.length) {
    throw new Error(
      `No @font-face for "${font.name}" in ${font.directory}/style.css`
    );
  }
  const face = pickRegularFace(faces);
  if (!face) {
    throw new Error(`No regular latin face found for "${font.name}"`);
  }
  const fontFile = fontFromBuffer(await readFile(join(publicDir, face.url)));
  const fallback = getFallbackMetricsFromFontFile(fontFile, font.category);

  metadata[font.name] = {
    preload: face.url,
  };
  fallbackCss.push(
    [
      `@font-face {`,
      `  font-family: "${font.name} Fallback";`,
      `  src: local("${fallback.fallbackFont}");`,
      `  ascent-override: ${fallback.ascentOverride};`,
      `  descent-override: ${fallback.descentOverride};`,
      `  line-gap-override: ${fallback.lineGapOverride};`,
      `  size-adjust: ${fallback.sizeAdjust};`,
      `}`,
    ].join('\n')
  );
}

const header = `This file is generated by scripts/fonts/generate-font-metadata.ts. Do not edit it by hand.`;

await writeFile(
  join(webappRoot, 'src/styles/fonts.generated.ts'),
  `// ${header}\n// The fallback metrics only go into fonts-fallback.css: this file ends up in\n// client bundles (the font picker), so it holds just what is used at runtime.\n\nexport const fontMetadata: Record<string, { preload: string }> = ${JSON.stringify(metadata, null, 2)};\n`
);
await writeFile(
  join(webappRoot, 'src/styles/fonts-fallback.css'),
  `/* ${header} */\n\n${fallbackCss.join('\n\n')}\n`
);

console.log(`Generated font metadata for ${allFonts.length} fonts`);
